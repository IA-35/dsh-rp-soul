/* 新引擎：真实时间工具。所有「现在」都是传进去的，跟机器的时钟、时区无关。 */
import { eq, ok, done } from './_check.mjs';
import * as T from '../lib/engine/core/time.js';

const now = '2026-11-11T21:40:30+08:00';

// ---- 1. 格式与换算 ----
eq(T.iso(T.ms('2026-11-11T13:40:30Z'), 480), '2026-11-11T21:40:30+08:00', '1. 毫秒按指定偏移写回 ISO');
eq(T.iso(T.ms('2026-11-11T13:40:30Z'), -300), '2026-11-11T08:40:30-05:00', '1. 负偏移也对');
eq(T.offsetOf(now), 480, '1. 读出 ISO 自带的偏移');
eq(T.offsetOf('2026-11-11T13:40:30Z'), 0, '1. Z 就是 0');
eq(T.addMinutes(now, 30), '2026-11-11T22:10:30+08:00', '1. 加分钟保留原来的偏移');
eq(T.addMinutes(now, 180), '2026-11-12T00:40:30+08:00', '1. 跨午夜');
ok(!T.isTime('明天'), '1. 认不出来的不算时刻');

// ---- 2. 隔了多久：往回走一律当 0 ----
eq(T.minutesBetween('2026-11-11T20:00:00+08:00', now), 100, '2. 一百分钟');
eq(T.minutesBetween(now, '2026-11-11T20:00:00+08:00'), 0, '2. 时间往回走（改了系统时间）当 0');
eq(T.minutesBetween('2026-11-08T21:40:30+08:00', now), 3 * 1440, '2. 隔三天');
eq(T.minutesBetween('乱写', now), 0, '2. 坏时刻当 0，不抛');
ok(T.before('2026-11-11T20:00:00+08:00', now), '2. 早于');
ok(!T.before(now, now), '2. 同一刻不算早于');

// ---- 3. 钟点与日历日按时刻自己的时区算 ----
eq(T.minuteOfDay(now), 21 * 60 + 40, '3. 当天第几分钟');
eq(T.dayKey('2026-11-11T23:59:00+08:00'), '2026-11-11', '3. 23:59 还是当天');
eq(T.dayKey('2026-11-11T16:30:00Z'), '2026-11-11', '3. 同一刻按 UTC 是 11 日');
eq(T.dayKey('2026-11-12T00:30:00+08:00'), '2026-11-12', '3. 过了午夜就是第二天');
eq(T.parseClock('23:00'), 1380, '3. HH:MM');
eq(T.parseClock('25:00'), null, '3. 不合法的钟点');

// ---- 4. 下一次到某个钟点 ----
eq(T.nextClock(now, '23:00'), '2026-11-11T23:00:00+08:00', '4. 今天还没到：今天的');
eq(T.nextClock(now, '07:30'), '2026-11-12T07:30:00+08:00', '4. 今天已经过了：明天的');
eq(T.nextClock(now, '21:40'), '2026-11-12T21:40:00+08:00', '4. 正好是这个钟点：算明天的');
eq(T.nextClock(now, 'x'), null, '4. 坏钟点返回 null');

// ---- 5. 一段相处、给人看的时刻 ----
ok(T.isNewScene(null, now), '5. 没有上一次就是新的一段');
ok(!T.isNewScene('2026-11-11T21:00:00+08:00', now), '5. 隔 40 分钟还是同一段');
ok(T.isNewScene('2026-11-11T20:40:00+08:00', now), '5. 隔 60 分钟就是新的一段');
eq(T.label('2026-11-11T08:05:00+08:00', now), '今天 08:05', '5. 今天');
eq(T.label('2026-11-10T23:10:00+08:00', now), '昨天 23:10', '5. 昨天');
eq(T.label('2026-11-09T21:40:00+08:00', now), '11月9日 21:40', '5. 更早写日期');
eq(T.ago('2026-11-11T21:40:00+08:00', now), '刚刚', '5. 刚刚');
eq(T.ago('2026-11-11T18:40:00+08:00', now), '3 小时前', '5. 几小时前');
eq(T.ago('2026-11-09T21:00:00+08:00', now), '2 天前', '5. 几天前');

// ---- 6. 快照用的粗时间：同一个时段里怎么走都不变 ----
eq(T.roughLabel(now, now), '今天晚上', '6. 21:40 是晚上');
eq(T.roughLabel('2026-11-11T16:17:00+08:00', now), '今天下午', '6. 16:17 是下午');
eq(T.roughLabel('2026-11-11T16:59:00+08:00', now), T.roughLabel('2026-11-11T13:00:00+08:00', now), '6. 下午里分钟走了，标签不变');
eq(T.roughLabel('2026-11-10T02:00:00+08:00', now), '昨天深夜', '6. 凌晨两点是深夜');
eq(T.roughLabel('2026-11-11T23:30:00+08:00', now), '今天深夜', '6. 23:30 也是深夜');
eq(T.roughLabel('2026-11-09T07:00:00+08:00', now), '11月9日清晨', '6. 更早的写日期');
eq(T.roughAgo('2026-11-11T21:05:00+08:00', now), '刚才', '6. 一小时以内都叫刚才');
eq(T.roughAgo('2026-11-11T18:40:00+08:00', now), '3 小时前', '6. 再往后按小时');

done('v2-time');
